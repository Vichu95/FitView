function smoothPath(pts) {
  const n = pts.length;
  const p = (i) => pts[(i + n) % n];
  let d = `M${p(0)[0]},${p(0)[1]}`;
  for (let i = 0; i < n; i++) {
    const [p0, p1, p2, p3] = [p(i - 1), p(i), p(i + 1), p(i + 2)];
    const c1 = [p1[0] + (p2[0] - p0[0]) / 6, p1[1] + (p2[1] - p0[1]) / 6];
    const c2 = [p2[0] - (p3[0] - p1[0]) / 6, p2[1] - (p3[1] - p1[1]) / 6];
    d += `C${c1[0].toFixed(1)},${c1[1].toFixed(1)} ${c2[0].toFixed(1)},${c2[1].toFixed(1)} ${p2[0]},${p2[1]}`;
  }
  return d + 'Z';
}

const mirror = (pts) => pts.map(([x, y]) => [200 - x, y]);
export const SIL_PATH = smoothPath([...SILHOUETTE, ...mirror(SILHOUETTE).reverse()]);

function buildView(regions) {
  return regions.map(([id, pts]) => ({ id, d: [smoothPath(pts), smoothPath(mirror(pts))] }));
}
// Also used by the canvas image export (as Path2D), so keep it plain path data.
export const VIEWS = { front: buildView(FRONT), back: buildView(BACK) };
export const BODY_W = 200;
export const BODY_H = 430;
export const DRAWN_MUSCLES = new Set([...FRONT, ...BACK].map(([id]) => id));

// fills: { muscleId: cssColor }. Muscles without a fill get the neutral base colour.
export function bodySvg(view, fills, label) {
  const paths = VIEWS[view].map(({ id, d }) => {
    const style = fills[id] ? ` style="fill:${fills[id]}"` : '';
    return d.map((dd) => `<path class="m" data-m="${id}" d="${dd}"${style}/>`).join('');
  }).join('');
  const detail = view === 'back'
    ? '<line class="detail" x1="100" y1="60" x2="100" y2="205"/>'
    : '<line class="detail" x1="100" y1="121" x2="100" y2="203"/>';
  return `<figure class="body-fig">
    <svg viewBox="0 0 200 430" role="img" aria-label="${label}">
      <path class="sil" d="${SIL_PATH}"/>
      <ellipse class="sil" cx="100" cy="26" rx="15" ry="19"/>
      ${paths}${detail}
    </svg>
    <figcaption>${label}</figcaption>
  </figure>`;
}
